/** Replaces %PAGE_VERSION% in index.html with the version (in the build and in the dev server). */
function injectVersion(): Plugin {
    return {
        name: 'inject-version',
        buildStart() {
            const version = describePageVersion();
            console.log(`Version: ${version}`);
            if (version.includes('-dirty')) {
                console.log(`Files changed since the commit:\n${uncommittedChanges()}`);
            }
        },
        transformIndexHtml: (html) => html.replace('%PAGE_VERSION%', escapeHtml(describePageVersion())),
    };
}

/**
 * Generates public/assets/data/index.json (list of Bibles) from the
 * *.ebf1.json files and settings.json, when the build and the dev server
 * start. Fails if the index cannot be generated.
 */
function generateBibleIndex(): Plugin {
    return {
        name: 'generate-bible-index',
        buildStart() {
            const entries = writeIndex();
            const defaultEntry = entries.find((entry) => entry.default);
            const defaultBible = defaultEntry ? `${defaultEntry.language}/${defaultEntry.slug}` : '';
            console.log(`index.json: ${entries.length} Bibles (default: ${defaultBible})`);
        },
    };
}

const EBF1_VALIDATOR_ID = 'virtual:ebf1-validator';

/**
 * Virtual module with the validator for the official EBF1 schema (from the
 * easy-bible-format package), generated by ajv as code: ajv itself is not in
 * the bundle, only the validator and two helpers from its runtime.
 */
function ebf1Validator(): Plugin {
    const resolvedId = `\0${EBF1_VALIDATOR_ID}`;
    return {
        name: 'ebf1-validator',
        resolveId: (id) => (id === EBF1_VALIDATOR_ID ? resolvedId : undefined),
        load(id) {
            if (id !== resolvedId) return undefined;
            const schemaFile = fileURLToPath(import.meta.resolve('easy-bible-format/ebf1-schema.json'));
            const schema = JSON.parse(readFileSync(schemaFile, 'utf8')) as object;
            const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true } });
            // The generated code uses require() for the runtime helpers; turned into imports for the bundle
            const imports: string[] = [];
            const code = standaloneCode(ajv, ajv.compile(schema)).replace(/require\("([^"]+)"\)/g, (_, path: string) => {
                const name = `runtime${imports.length}`;
                imports.push(`import * as ${name} from '${path}';`);
                return name;
            });
            return `${imports.join('\n')}\n${code}`;
        },
    };
}

/** Minifies the published index.html (including inline scripts) and manifest.json. */
function minifyStaticFiles(): Plugin {
    let outDir = 'dist';
    return {
        name: 'minify-static-files',
        apply: 'build',
        configResolved(config) {
            outDir = config.build.outDir;
        },
        transformIndexHtml: {
            order: 'post',
            handler: (html) =>
                minify(html, {
                    collapseWhitespace: true,
                    removeComments: true,
                    minifyCSS: true,
                    minifyJS: true,
                }),
        },
        writeBundle() {
            const manifest = join(outDir, 'manifest.json');
            writeFileSync(manifest, JSON.stringify(JSON.parse(readFileSync(manifest, 'utf8'))));
        },
    };
}

